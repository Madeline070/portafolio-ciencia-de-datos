-- CONSULTAS_VENTAS.sql
-- Selecciona en SSMS la base de datos que contiene las cinco tablas del proyecto.

-- EJERCICIO 1: Ventas por categoría
SELECT C.CATEGORY AS Categoria, SUM(F.TOTAL_VALUE_SALES) AS Ventas_Totales
FROM dbo.FACT_SALES AS F
INNER JOIN dbo.DIM_PRODUCT AS P ON F.ITEM_CODE_BASE = P.ITEM_CODE_BASE
INNER JOIN dbo.DIM_CATEGORY AS C ON P.CATEGORY = C.ID_CATEGORY
GROUP BY C.CATEGORY
ORDER BY Ventas_Totales DESC;
GO

-- EJERCICIO 2: Ventas por región
SELECT REGION, SUM(TOTAL_VALUE_SALES) AS Ventas_Totales
FROM dbo.FACT_SALES
GROUP BY REGION
ORDER BY Ventas_Totales DESC;
GO

-- EJERCICIO 3: Ventas por año y mes
SELECT C.YEAR AS Anio, C.MONTH AS Mes, SUM(F.TOTAL_VALUE_SALES) AS Ventas_Totales
FROM dbo.FACT_SALES AS F
INNER JOIN dbo.DIM_CALENDAR AS C ON F.WEEK = C.WEEK
GROUP BY C.YEAR, C.MONTH
ORDER BY C.YEAR, C.MONTH;
GO

-- EJERCICIO 4: Cantidad de productos por categoría
SELECT C.ID_CATEGORY, C.CATEGORY AS Nombre_Categoria, COUNT(P.ITEM) AS Total_Productos
FROM dbo.DIM_CATEGORY AS C
LEFT JOIN dbo.DIM_PRODUCT AS P ON P.CATEGORY = C.ID_CATEGORY
GROUP BY C.ID_CATEGORY, C.CATEGORY
ORDER BY C.ID_CATEGORY;
GO

-- EJERCICIO 5: Productos por código de categoría
SELECT CATEGORY, COUNT(*) AS Total_Productos
FROM dbo.DIM_PRODUCT
GROUP BY CATEGORY
ORDER BY CATEGORY;
GO

-- EJERCICIO 6: Ventas por semana
SELECT WEEK, SUM(TOTAL_VALUE_SALES) AS Ventas_Totales
FROM dbo.FACT_SALES
GROUP BY WEEK
ORDER BY WEEK;
GO

-- EJERCICIO 7: Los 10 productos con mayores ventas
SELECT TOP 10 ITEM_CODE, SUM(TOTAL_VALUE_SALES) AS Ventas_Totales
FROM dbo.FACT_SALES
GROUP BY ITEM_CODE
ORDER BY Ventas_Totales DESC;
GO

-- EJERCICIO 8: Ventas por categoría y región
SELECT C.CATEGORY AS Categoria, F.REGION AS Region,
       SUM(F.TOTAL_VALUE_SALES) AS Ventas_Totales
FROM dbo.FACT_SALES AS F
INNER JOIN dbo.DIM_PRODUCT AS P ON F.ITEM_CODE_BASE = P.ITEM_CODE_BASE
INNER JOIN dbo.DIM_CATEGORY AS C ON P.CATEGORY = C.ID_CATEGORY
GROUP BY C.CATEGORY, F.REGION
ORDER BY Ventas_Totales DESC;
GO

-- EJERCICIO 9: Ventas totales por año
SELECT C.YEAR AS Anio, SUM(F.TOTAL_VALUE_SALES) AS Ventas_Totales
FROM dbo.FACT_SALES AS F
INNER JOIN dbo.DIM_CALENDAR AS C ON F.WEEK = C.WEEK
GROUP BY C.YEAR
ORDER BY C.YEAR;
GO

-- EJERCICIO 10: Los 10 productos con más unidades vendidas
SELECT TOP 10 ITEM_CODE, SUM(TOTAL_UNIT_SALES) AS Unidades_Vendidas
FROM dbo.FACT_SALES
GROUP BY ITEM_CODE
ORDER BY Unidades_Vendidas DESC;
GO

-- EJERCICIO 11: Promedio de ventas por región
SELECT REGION, AVG(TOTAL_VALUE_SALES) AS Promedio_Ventas,
       SUM(TOTAL_VALUE_SALES) AS Ventas_Totales, COUNT(*) AS Total_Registros
FROM dbo.FACT_SALES
GROUP BY REGION
ORDER BY Promedio_Ventas DESC;
GO

-- EJERCICIO 12: Ventas por año y región
SELECT C.YEAR AS Anio, F.REGION AS Region,
       SUM(F.TOTAL_VALUE_SALES) AS Ventas_Totales
FROM dbo.FACT_SALES AS F
INNER JOIN dbo.DIM_CALENDAR AS C ON F.WEEK = C.WEEK
GROUP BY C.YEAR, F.REGION
ORDER BY C.YEAR, Ventas_Totales DESC;
GO
